import { z } from "zod"
import { registerAppTool } from "@modelcontextprotocol/ext-apps/server"
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js"
import type { SupabaseClient } from "@supabase/supabase-js"
import type { Database, McpContext } from "@/lib/database.types"
import {
  routingRequestSchema,
  resolveExecutionRoute,
} from "@/lib/media/routing"
import { getMediaAccess } from "@/lib/media/service"
import {
  prepareNativeOutput,
  finishNativeOutput,
  getNativeSnapshot,
} from "@/lib/media/native"
import {
  nativeInputSchema,
  nativeHostSchema,
  generationSnapshotSchema,
} from "@/lib/media/contracts"
import { GENERATION_RESOURCE_URI } from "@/lib/mcp/generation-resource"

export const NATIVE_TOOLS = [
  "create_native_output",
  "complete_native_output",
  "get_native_generation",
]
const readOnly = {
  readOnlyHint: true,
  destructiveHint: false,
  idempotentHint: true,
  openWorldHint: false,
}
const meta = { securitySchemes: [{ type: "oauth2", scopes: ["email"] }] }
const safely = async (callback: () => Promise<Record<string, unknown>>) => {
  try {
    const data = await callback()
    return {
      content: [{ type: "text" as const, text: JSON.stringify(data) }],
      structuredContent: data,
    }
  } catch (error) {
    return {
      isError: true,
      content: [
        {
          type: "text" as const,
          text:
            error instanceof Error
              ? error.message
              : "Unable to open the native result",
        },
      ],
    }
  }
}

export const registerNativeTools = (
  server: McpServer,
  client: SupabaseClient<Database>,
  context: McpContext,
) => {
  server.registerTool(
    "resolve_generation_route",
    {
      title: "Choose generation route",
      description:
        "Choose native-first or a reviewed API fallback using the current host's actually exposed tools. Native availability is reported by the assistant, not inferred from the backend. Never silently substitute an explicitly requested model, bypass a safety refusal or duplicate an uncertain native generation.",
      inputSchema: {
        operation: z
          .enum([
            "image",
            "video",
            "speech",
            "music",
            "sound_effects",
            "editing",
          ])
          .default("image"),
        ...routingRequestSchema.shape,
      },
      annotations: readOnly,
      _meta: meta,
    },
    async (args) =>
      safely(async () => {
        const access = await getMediaAccess(client, context.workspace.id)
        const supportedModel =
          !args.requested_model ||
          ["image/nano-banana-2", "nano-banana-2", "Nano Banana 2"].includes(
            args.requested_model,
          )
        const providerAvailable =
          supportedModel &&
          args.operation === "image" &&
          access.enabled &&
          access.can_prepare &&
          access.provider_budget_enabled &&
          access.credit_pricing_enabled &&
          access.provider_ready
        return {
          ...resolveExecutionRoute(
            routingRequestSchema.parse(args),
            providerAvailable,
          ),
          policy: "native_first",
          native_discovery:
            "Inspect the actual host tool inventory; installed skills alone do not prove a native generator exists.",
          provider_available: providerAvailable,
          native_usage:
            "Host plan limits or charges may apply; CreativeOtter does not charge provider inference for this route.",
        }
      }),
  )
  server.registerTool(
    "create_native_output",
    {
      title: "Save native image",
      description:
        "Prepare a private upload for an image already generated by an actual native host tool. Does not generate an image or call a provider. Send the exact creation prompt and only a model name actually reported by the host. PUT the existing image bytes to signed_url, then call complete_native_output. Reuse request_key for retries; do not regenerate after upload failure.",
      inputSchema: {
        ...nativeInputSchema.shape,
        host: nativeHostSchema,
        reported_model: z.string().min(1).max(120).nullable().default(null),
        mime_type: z
          .enum(["image/png", "image/jpeg", "image/webp"])
          .default("image/png"),
        request_key: z.uuid(),
      },
      annotations: { ...readOnly, readOnlyHint: false },
      _meta: meta,
    },
    async (args) =>
      safely(async () => {
        const input = nativeInputSchema.parse({
          prompt: args.prompt,
          aspect_ratio: args.aspect_ratio,
          resolution: args.resolution,
          reference_asset_ids: args.reference_asset_ids,
        })
        return prepareNativeOutput(
          client,
          context.workspace.id,
          input,
          args.host,
          args.reported_model,
          args.mime_type,
          args.request_key,
        )
      }),
  )
  registerAppTool(
    server,
    "complete_native_output",
    {
      title: "Open native image",
      description:
        "Validate and save an already-uploaded native image, then open CreativeOtter's Output/Inputs panel. Never invokes provider inference. A successful file upload is not ready until this tool confirms saved output.",
      inputSchema: { generation_id: z.uuid() },
      outputSchema: generationSnapshotSchema.shape,
      annotations: { ...readOnly, readOnlyHint: false },
      _meta: {
        ...meta,
        ui: {
          resourceUri: GENERATION_RESOURCE_URI,
          visibility: ["model", "app"],
        },
        "openai/outputTemplate": GENERATION_RESOURCE_URI,
        "openai/widgetAccessible": true,
        "openai/toolInvocation/invoking": "Saving your native image…",
        "openai/toolInvocation/invoked": "Opened your native image",
      },
    },
    async ({ generation_id }) =>
      safely(() =>
        finishNativeOutput(client, context.workspace.id, generation_id),
      ),
  )
  server.registerTool(
    "get_native_generation",
    {
      title: "Native image result",
      description:
        "Read an existing native generation and refresh its private preview/download links. Never starts generation or calls a paid provider.",
      inputSchema: { generation_id: z.uuid() },
      annotations: readOnly,
      _meta: {
        ...meta,
        ui: { visibility: ["model", "app"] },
        "openai/widgetAccessible": true,
      },
    },
    async ({ generation_id }) =>
      safely(() =>
        getNativeSnapshot(client, context.workspace.id, generation_id),
      ),
  )
}
